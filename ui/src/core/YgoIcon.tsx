export type YgoIconName =
    "collapse"
    | "expand"
    | "help-outline"
    | "help-fill"
    | "double-arrow-right"
    | "double-arrow-left"
    | "cog"
    | "trash"
    | "xcircle"
    | "checkmark"
    | "user"
    | "eye"

export type YgoIconsProps = {
    icon: YgoIconName
    size: number | undefined
    classNames?: string | undefined
    onClick?: React.MouseEventHandler<any>
};

function YgoIcon(props: YgoIconsProps) {
    const size = props.size ? props.size : 18;
    const classNames = props.classNames ? props.classNames : "";

    function getIcon(icon: YgoIconName): JSX.Element {
        switch (icon) {
            case "collapse":
                return CollapsedIcon
            case "expand":
                return ExpandIcon
            case "help-fill":
                return HelpFillIcon
            case "help-outline":
                return HelpOutlineIcon
            case "double-arrow-right":
                return DoubleArrowRight
            case "double-arrow-left":
                return DoubleArrowLeft
            case "cog":
                return Cog
            case "trash":
                return Trash
            case "xcircle":
                return X_Circle
            case "checkmark":
                return Checkmark
            case "user":
                return User
            case "eye":
                return Eye
            default:
                console.error("Icon not found: " + icon)
                return <div className={"bg-red-500 m-2 rounded"}>ICON NOT FOUND</div>
        }
    }

    if (props.onClick) {
        return <SvgIconButton onClick={props.onClick} size={size}
                              classNames={classNames}>
            {getIcon(props.icon)}
        </SvgIconButton>
    }

    return <SvgIconButton size={size}
                          classNames={classNames}>
        {getIcon(props.icon)}
    </SvgIconButton>
}

export default YgoIcon
